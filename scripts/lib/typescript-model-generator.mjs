function assertSchemaSet(schemaSources, epoch) {
  if (!Array.isArray(schemaSources) || schemaSources.length === 0) {
    throw new Error('TypeScript model generation requires at least one canonical schema.');
  }
  const files = new Set();
  const identifiers = new Set();
  for (const source of schemaSources) {
    if (!/^[a-z0-9-]+\.schema\.json$/u.test(source.file)) {
      throw new Error(`Unsupported canonical schema filename ${String(source.file)}.`);
    }
    if (files.has(source.file)) {
      throw new Error(`Duplicate canonical schema filename ${source.file}.`);
    }
    files.add(source.file);
    if (typeof source.schema?.$id !== 'string' || source.schema.$id.length === 0) {
      throw new Error(`Canonical schema ${source.file} has no nonempty $id.`);
    }
    if (!source.schema.$id.startsWith(epoch)) {
      throw new Error(`Canonical schema ${source.file} is outside schema epoch ${epoch}.`);
    }
    if (identifiers.has(source.schema.$id)) {
      throw new Error(`Duplicate canonical schema identifier ${source.schema.$id}.`);
    }
    identifiers.add(source.schema.$id);
  }
}

function assertSupportedSchema(schema, file, pointer) {
  if (typeof schema === 'boolean') return;
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new Error(`${file}${pointer} is not a JSON Schema object or boolean.`);
  }
  for (const keyword of Object.keys(schema)) {
    if (!supportedKeywords.has(keyword)) {
      throw new Error(`Unsupported JSON Schema keyword ${keyword} at ${file}${pointer}.`);
    }
  }
  if ('type' in schema) {
    const values = Array.isArray(schema.type) ? schema.type : [schema.type];
    if (
      values.length === 0 ||
      values.some(
        (value) =>
          typeof value !== 'string' ||
          !['array', 'boolean', 'integer', 'null', 'number', 'object', 'string'].includes(value),
      )
    ) {
      throw new Error(`Unsupported type declaration at ${file}${pointer}.`);
    }
  }
  for (const mapKeyword of ['$defs', 'properties']) {
    const entries = schema[mapKeyword];
    if (entries === undefined) continue;
    if (entries === null || typeof entries !== 'object' || Array.isArray(entries)) {
      throw new Error(`${mapKeyword} at ${file}${pointer} must be an object.`);
    }
    for (const [name, child] of Object.entries(entries)) {
      assertSupportedSchema(
        child,
        file,
        `${pointer}/${escapePointer(mapKeyword)}/${escapePointer(name)}`,
      );
    }
  }
  for (const childKeyword of [
    'additionalProperties',
    'else',
    'if',
    'items',
    'not',
    'propertyNames',
    'then',
  ]) {
    if (schema[childKeyword] !== undefined) {
      assertSupportedSchema(
        schema[childKeyword],
        file,
        `${pointer}/${escapePointer(childKeyword)}`,
      );
    }
  }
  for (const arrayKeyword of ['allOf', 'anyOf', 'oneOf', 'prefixItems']) {
    const children = schema[arrayKeyword];
    if (children === undefined) continue;
    if (!Array.isArray(children)) {
      throw new Error(`${arrayKeyword} at ${file}${pointer} must be an array.`);
    }
    children.forEach((child, index) =>
      assertSupportedSchema(child, file, `${pointer}/${escapePointer(arrayKeyword)}/${index}`),
    );
  }
}

function renderDeclaration({ context, description, file, name, schema }) {
  const documentation =
    typeof description === 'string' && description.length > 0
      ? `/** ${description.replaceAll('*/', '*\\/')} */\n`
      : '';
  return `${documentation}export type ${name} = ${renderSchema(schema, file, context)};`;
}

function renderSchema(schema, file, context) {
  if (schema === true) return 'GeneratedJsonValue';
  if (schema === false) return 'never';

  const constraints = [];
  if (typeof schema.$ref === 'string') {
    constraints.push(renderReference(schema.$ref, file, context));
  }
  if ('const' in schema) constraints.push(renderLiteral(schema.const));
  if (Array.isArray(schema.enum)) {
    constraints.push(union(schema.enum.map((value) => renderLiteral(value))));
  }
  if (Array.isArray(schema.oneOf)) {
    constraints.push(union(schema.oneOf.map((child) => renderSchema(child, file, context))));
  }
  if (Array.isArray(schema.anyOf)) {
    constraints.push(union(schema.anyOf.map((child) => renderSchema(child, file, context))));
  }

  const structural = renderStructuralSchema(schema, file, context);
  if (structural !== undefined) constraints.push(structural);

  if (Array.isArray(schema.allOf)) {
    for (const child of schema.allOf) {
      const rendered = renderSchema(child, file, context);
      if (rendered !== 'GeneratedJsonValue') constraints.push(rendered);
    }
  }

  const distinct = [...new Set(constraints)];
  if (distinct.length === 0) {
    const meaningfulKeywords = Object.keys(schema).filter(
      (keyword) =>
        !annotationKeywords.has(keyword) &&
        ![
          '$defs',
          'additionalProperties',
          'dependentRequired',
          'else',
          'if',
          'items',
          'not',
          'prefixItems',
          'properties',
          'required',
          'then',
          'exclusiveMaximum',
          'exclusiveMinimum',
          'maxItems',
          'maxLength',
          'maxProperties',
          'maximum',
          'minItems',
          'minLength',
          'minProperties',
          'minimum',
          'multipleOf',
          'pattern',
          'propertyNames',
          'uniqueItems',
        ].includes(keyword),
    );
    if (meaningfulKeywords.length > 0) {
      throw new Error(
        `Schema at ${file} contains unprojected structural keywords: ${meaningfulKeywords.join(', ')}.`,
      );
    }
    return 'GeneratedJsonValue';
  }
  return intersection(distinct);
}

function renderStructuralSchema(schema, file, context) {
  if (Array.isArray(schema.type)) {
    return union(schema.type.map((type) => renderType(type, schema, file, context)));
  }
  if (typeof schema.type === 'string') return renderType(schema.type, schema, file, context);
  // Object and array keywords apply only to instances of their respective kind. Without an
  // explicit type, scalars remain schema-valid, so inferring an object or array here would create
  // a generated type that falsely excludes valid JSON. Runtime JSON Schema validation retains the
  // narrower conditional meaning of these keywords.
  return undefined;
}

function renderType(type, schema, file, context) {
  switch (type) {
    case 'array':
      return renderArray(schema, file, context);
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'null':
      return 'null';
    case 'object':
      return renderObject(schema, file, context);
    case 'string':
      return 'string';
    default:
      throw new Error(`Unsupported JSON Schema type ${String(type)} in ${file}.`);
  }
}

function renderObject(schema, file, context) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const propertyEntries = Object.entries(properties)
    .sort(([left], [right]) => compareCodeUnits(left, right))
    .map(([name, child]) => ({ name, type: renderSchema(child, file, context) }));
  const members = propertyEntries.map(({ name, type }) => {
    const optional = required.has(name) ? '' : '?';
    return `${JSON.stringify(name)}${optional}: ${type};`;
  });

  if (members.length === 0 && typeof schema.additionalProperties === 'object') {
    return `{ [key: string]: ${renderSchema(schema.additionalProperties, file, context)} }`;
  }
  if (members.length === 0 && schema.additionalProperties === false) {
    return 'Record<string, never>';
  }
  if (members.length === 0) return '{ [key: string]: GeneratedJsonValue }';

  if (schema.additionalProperties !== false) {
    const additionalType =
      typeof schema.additionalProperties === 'object'
        ? renderSchema(schema.additionalProperties, file, context)
        : 'GeneratedJsonValue';
    // TypeScript cannot subtract the declared property names from a string index signature.
    // Including their exact value types keeps every schema-valid object assignable while the
    // runtime schema retains authority over the values of genuinely additional members.
    members.push(
      `[key: string]: ${union([additionalType, ...propertyEntries.map(({ type }) => type)])};`,
    );
  }

  return `{ ${members.join('\n')} }`;
}

function renderArray(schema, file, context) {
  const minimum = schema.minItems ?? 0;
  if (!Number.isSafeInteger(minimum) || minimum < 0) {
    throw new Error(`minItems in ${file} must be a non-negative safe integer.`);
  }
  const prefix = Array.isArray(schema.prefixItems)
    ? schema.prefixItems.map((child) => renderSchema(child, file, context))
    : [];
  if (prefix.length > 0) {
    if (schema.items === false && minimum > prefix.length) return 'never';
    const requiredPrefixLength = Math.min(minimum, prefix.length);
    const tuple = prefix.map((type, index) =>
      index < requiredPrefixLength ? type : `${parenthesize(type)}?`,
    );
    if (schema.items === false) return `[${tuple.join(', ')}]`;
    const rest =
      schema.items === undefined || schema.items === true
        ? 'GeneratedJsonValue'
        : renderSchema(schema.items, file, context);
    for (let index = prefix.length; index < minimum; index += 1) tuple.push(rest);
    tuple.push(`...${parenthesize(rest)}[]`);
    return `[${tuple.join(', ')}]`;
  }
  const item =
    schema.items === undefined || schema.items === true
      ? 'GeneratedJsonValue'
      : schema.items === false
        ? 'never'
        : renderSchema(schema.items, file, context);
  if (item === 'never') return minimum === 0 ? '[]' : 'never';
  if (minimum === 0) return `${parenthesize(item)}[]`;
  return `[${Array.from({ length: minimum }, () => item).join(', ')}, ...${parenthesize(item)}[]]`;
}

function renderReference(reference, currentFile, context) {
  const hashIndex = reference.indexOf('#');
  const file = hashIndex === -1 ? reference : reference.slice(0, hashIndex);
  const fragment = hashIndex === -1 ? '' : reference.slice(hashIndex + 1);
  const targetFile = file.length === 0 ? currentFile : file;
  const targetSchema = context.schemas.get(targetFile);
  if (targetSchema === undefined) {
    throw new Error(`Unresolved schema reference ${reference} from ${currentFile}.`);
  }
  if (fragment.length === 0) return modelName(targetFile);
  const pointer = decodeURIComponent(fragment);
  const segments = pointer
    .split('/')
    .slice(1)
    .map((segment) => segment.replaceAll('~1', '/').replaceAll('~0', '~'));
  if (segments.length === 2 && segments[0] === '$defs') {
    if (targetSchema.$defs?.[segments[1]] === undefined) {
      throw new Error(`Unresolved schema definition ${reference} from ${currentFile}.`);
    }
    return definitionModelName(targetFile, segments[1]);
  }
  let target = targetSchema;
  for (const segment of segments) {
    if (target === null || typeof target !== 'object' || !(segment in target)) {
      throw new Error(`Unresolved schema pointer ${reference} from ${currentFile}.`);
    }
    target = target[segment];
  }
  return renderSchema(target, targetFile, context);
}

function renderLiteral(value) {
  if (value === null || typeof value === 'boolean' || typeof value === 'string') {
    return JSON.stringify(value);
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value))
      throw new Error('JSON Schema literals must contain finite numbers.');
    return Object.is(value, -0) ? '-0' : String(value);
  }
  if (Array.isArray(value)) return `[${value.map((item) => renderLiteral(item)).join(', ')}]`;
  if (value !== null && typeof value === 'object') {
    const members = Object.entries(value)
      .sort(([left], [right]) => compareCodeUnits(left, right))
      .map(([key, child]) => `${JSON.stringify(key)}: ${renderLiteral(child)};`);
    return `{ ${members.join('\n')} }`;
  }
  throw new Error(`Unsupported non-JSON literal ${String(value)}.`);
}

function modelName(file) {
  return `Generated${pascalCase(file.replace(/\.schema\.json$/u, ''))}`;
}

function definitionModelName(file, definition) {
  return `${modelName(file)}${pascalCase(definition)}`;
}

function pascalCase(value) {
  const result = value
    .split(/[^A-Za-z0-9]+/u)
    .filter((part) => part.length > 0)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('');
  if (result.length === 0 || /^[0-9]/u.test(result)) {
    throw new Error(`Cannot derive a TypeScript identifier from ${value}.`);
  }
  return result;
}

function union(types) {
  const distinct = [...new Set(types)];
  if (distinct.length === 0) return 'never';
  if (distinct.length === 1) return distinct[0];
  return `(${distinct.join(' | ')})`;
}

function intersection(types) {
  if (types.length === 1) return types[0];
  return `(${types.join(' & ')})`;
}

function parenthesize(type) {
  return type.startsWith('(') ? type : `(${type})`;
}

function escapePointer(value) {
  return value.replaceAll('~', '~0').replaceAll('/', '~1');
}

function compareCodeUnits(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
